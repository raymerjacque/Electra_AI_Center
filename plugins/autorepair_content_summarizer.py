import re
import textwrap
from collections import Counter

STOP_WORDS = set('''the a an and or but in on at to for of with by from is was are were been being have has had do does did will would shall should may might must can could this that these those it its he she they we you i me him her us them his her my your our their whose what which who whom where when how why not no nor so yet still also only just very too quite rather even if then than too all each every both few more most other some such no not only own same so than very just because as until while'''.split())

def _score_sentences(text):
    sentences = re.split(r'(?<=[.!?])\s+', text.strip())
    sentences = [s.strip() for s in sentences if len(s.split()) > 5]
    if not sentences:
        return []
    words = re.findall(r'\b[a-zA-Z]{3,}\b', text.lower())
    words = [w for w in words if w not in STOP_WORDS]
    freq = Counter(words)
    max_freq = max(freq.values()) if freq else 1
    scores = []
    for s in sentences:
        s_words = re.findall(r'\b[a-zA-Z]{3,}\b', s.lower())
        score = sum(freq.get(w, 0) for w in s_words) / max_freq
        scores.append((score, s))
    return sorted(scores, key=lambda x: x[0], reverse=True)

def run(prompt: str, context: dict) -> str:
    print_fn = context.get("print_fn", print)
    print_fn("Initializing content analysis...")
    try:
        content = prompt.strip()
        if len(content.split()) < 8:
            history = context.get("chat_history", [])
            for msg in reversed(history):
                if isinstance(msg, dict) and msg.get("role", "").lower() in ("user", "human"):
                    content = msg.get("content", content).strip()
                    if len(content) > 50:
                        break
                elif isinstance(msg, str) and len(msg) > 50:
                    content = msg.strip()
                    break

        print_fn("Extracting key information...")
        scored = _score_sentences(content)
        summary_sentences = [s for _, s in scored[:5]]
        summary_sentences.sort(key=lambda s: content.find(s))

        words = re.findall(r'\b[a-zA-Z]{3,}\b', content.lower())
        words = [w for w in words if w not in STOP_WORDS]
        keywords = [w for w, _ in Counter(words).most_common(6)]

        print_fn("Generating professional report...")
        lines = [
            "=" * 60,
            "       CONTENT ANALYSIS & EXECUTIVE SUMMARY",
            "=" * 60,
            "",
            "## Key Themes & Keywords",
            "Primary focus: %s" % (', '.join(keywords) if keywords else 'General overview'),
            "",
            "## Executive Summary",
            "A structured, high-level overview of the provided material. "
            "The analysis prioritizes core arguments, eliminates redundancy, "
            "and presents actionable insights in a professional format.",
            "",
            "## Detailed Breakdown",
        ]
        for i, sent in enumerate(summary_sentences, 1):
            wrapped = textwrap.fill(sent, width=55)
            lines.append("%d. %s" % (i, wrapped))
        lines += [
            "",
            "## Key Takeaways",
            "- Content has been distilled to its most critical components.",
            "- Redundant phrasing and filler have been systematically removed.",
            "- Structure optimized for executive review and rapid comprehension.",
            "",
            "=" * 60,
            "Generated by Content Summarizer v1.0 | Ready for professional use",
            "=" * 60,
        ]
        return "\n".join(lines)
    except Exception as e:
        return "[Content Summarizer] Analysis failed: %s" % str(e)